from (values
  ('INDUSTRY', 'University default - industry'),
  ('GRAD',     'University default - graduate school')
) as v(goal_type, name)
where not exists (
  select 1 from roadmap_templates t
  where t.school_id is null and t.major_id is null and t.goal_type = v.goal_type
);

