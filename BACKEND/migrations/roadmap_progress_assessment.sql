-- ---------------------------------------------------------------------
-- [1] ALTER: student_milestones
-- The description and competencies are copied onto the row (like name and
-- category) so a student's roadmap stays stable when a template changes.
-- competency_ids holds skills.skill_id values of competency rows (type = true).
-- ---------------------------------------------------------------------
alter table student_milestones
  add column if not exists description    text,
  add column if not exists source         varchar(12) not null default 'TEMPLATE'
    check (source in ('TEMPLATE', 'COURSE', 'GAP', 'EXPERIENCE', 'CUSTOM')),
  add column if not exists competency_ids bigint[] not null default '{}';


-- ---------------------------------------------------------------------
-- [2] ALTER: template_milestones
-- A milestone with gap_competency_id is only added to a roadmap when the
-- student rates that competency 1 or 2 in the skill assessment.
-- ---------------------------------------------------------------------
alter table template_milestones
  add column if not exists gap_competency_id bigint references skills(skill_id);


-- ---------------------------------------------------------------------
-- [3] NEW TABLE: student_assessments  (one row per completed assessment)
-- ratings: { "<competency skill_id>": 1..4 }
-- experience: [{ "kind": "INTERNSHIP" | "JOB" | "CERT" | "PROJECT", "title": "..." }]
-- ---------------------------------------------------------------------
create table if not exists student_assessments (
  id            bigint generated by default as identity primary key,
  student_id    bigint not null references student(student_id) on delete cascade,
  ratings       jsonb  not null,
  experience    jsonb  not null default '[]'::jsonb,
  completed_at  timestamptz not null default now()
);

create index if not exists student_assessments_student_idx
  on student_assessments (student_id, completed_at desc);


-- ---------------------------------------------------------------------
-- [4] student_course_history: courses a student has taken or is taking.
-- Created here if the base schema does not have it yet; the unique index
-- lets the assessment upsert one row per (student, course).
-- ---------------------------------------------------------------------
create table if not exists student_course_history (
  student_id  bigint not null references student(student_id) on delete cascade,
  course_id   bigint not null references courses(course_id) on delete cascade,
  status      varchar(12) not null default 'COMPLETED'
              check (status in ('COMPLETED', 'IN_PROGRESS'))
);

create unique index if not exists student_course_history_student_course
  on student_course_history (student_id, course_id);


-- ---------------------------------------------------------------------
-- [5] SEED: university default roadmap templates (one per goal type)
-- These are used until a school or major gets its own template; every
-- fallback is recorded in roadmap_template_gaps for Career Development.
-- Course milestones are not seeded: they come from major_courses.
-- ---------------------------------------------------------------------
insert into roadmap_templates (school_id, major_id, goal_type, name)
