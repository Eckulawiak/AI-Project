-- =====================================================================
-- Career Services - faculty/advisor review of a student's skills
-- Run after roadmap_progress_assessment.sql. Safe to re-run.
--
-- A faculty member or advisor picks a student on their Student Reviews
-- page and rates the student's eight career skills based on what they
-- have seen. The student sees those ratings next to their own on the
-- Advisor Feedback page. No invitation is needed.
-- =====================================================================

create table if not exists skill_reviews (
  id            bigint generated by default as identity primary key,
  student_id    bigint not null references student(student_id) on delete cascade,
  faculty_id    bigint not null references faculty_admin(faculty_id) on delete cascade,
  status        varchar(10) not null default 'COMPLETE'
                check (status in ('PENDING', 'COMPLETE')),
  -- { "<competency skill_id>": 1..4 }, filled in by the faculty member
  ratings       jsonb not null default '{}'::jsonb,
  comment       text,
  requested_at  timestamptz not null default now(),
  completed_at  timestamptz
);

-- one review per student and faculty member; the faculty member can
-- update it later
create unique index if not exists skill_reviews_student_faculty
  on skill_reviews (student_id, faculty_id);

create index if not exists skill_reviews_faculty_idx
  on skill_reviews (faculty_id, status);

-- Reviews are written directly by faculty, so a saved review is complete.
-- (Earlier versions of this file defaulted to PENDING for invitations.)
alter table skill_reviews alter column status set default 'COMPLETE';
